-- Creates the tables, storage buckets and permissions the app needs.

-- ========== TABLES ==========
create table if not exists public.urls (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  original_url text not null,
  short_url text not null unique,
  custom_url text unique,
  user_id uuid not null references auth.users (id) on delete cascade,
  title text not null,
  qr text
);

create table if not exists public.clicks (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  url_id bigint not null references public.urls (id) on delete cascade,
  city text,
  country text,
  device text
);

-- ========== ROW LEVEL SECURITY ==========
alter table public.urls enable row level security;
alter table public.clicks enable row level security;

-- Anyone can look up a short link (needed to redirect visitors)
create policy "Anyone can read urls" on public.urls
  for select to anon, authenticated using (true);

-- Logged-in users can create and delete only their own links
create policy "Users create own urls" on public.urls
  for insert to authenticated with check (auth.uid() = user_id);

create policy "Users delete own urls" on public.urls
  for delete to authenticated using (auth.uid() = user_id);

-- Any visitor of a short link records a click
create policy "Anyone can record clicks" on public.clicks
  for insert to anon, authenticated with check (true);

-- Users only see stats for their own links
create policy "Users read clicks of own urls" on public.clicks
  for select to authenticated
  using (url_id in (select id from public.urls where user_id = auth.uid()));

-- ========== STORAGE BUCKETS ==========
insert into storage.buckets (id, name, public)
values ('qrs', 'qrs', true), ('profile_pic', 'profile_pic', true)
on conflict (id) do nothing;

-- Profile picture is uploaded during sign-up (before the user is logged in)
create policy "Anyone can upload profile pics" on storage.objects
  for insert to anon, authenticated with check (bucket_id = 'profile_pic');

-- QR codes are uploaded by logged-in users when creating a link
create policy "Users can upload qr codes" on storage.objects
  for insert to authenticated with check (bucket_id = 'qrs');
